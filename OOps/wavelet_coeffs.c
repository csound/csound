const cs_float *swt_get_coefficients(int32_t family, int32_t order,
                                  int32_t *length) {
  const cs_float *coeffs = NULL;
  int32_t size = 0;
  switch (family) {
  case SWT_FAMILY_HAAR:
    if (order == 1) { coeffs = swt_cf_db1; size = 2; }
    break;
  case SWT_FAMILY_DB:
    switch (order) {
    case 1: coeffs = swt_cf_db1; size = 2; break;
    case 2: coeffs = swt_cf_db2; size = 4; break;
    case 3: coeffs = swt_cf_db3; size = 6; break;
    case 4: coeffs = swt_cf_db4; size = 8; break;
    case 5: coeffs = swt_cf_db5; size = 10; break;
    case 6: coeffs = swt_cf_db6; size = 12; break;
    case 7: coeffs = swt_cf_db7; size = 14; break;
    case 8: coeffs = swt_cf_db8; size = 16; break;
    }
    break;
  case SWT_FAMILY_SYMLET:
    switch (order) {
    case 2: coeffs = swt_cf_sym2; size = 4; break;
    case 3: coeffs = swt_cf_sym3; size = 6; break;
    case 4: coeffs = swt_cf_sym4; size = 8; break;
    case 5: coeffs = swt_cf_sym5; size = 10; break;
    case 6: coeffs = swt_cf_sym6; size = 12; break;
    case 7: coeffs = swt_cf_sym7; size = 14; break;
    case 8: coeffs = swt_cf_sym8; size = 16; break;
    }
    break;
  case SWT_FAMILY_COIFLET:
    switch (order) {
    case 1: coeffs = swt_cf_coif1; size = 6; break;
    case 2: coeffs = swt_cf_coif2; size = 12; break;
    case 3: coeffs = swt_cf_coif3; size = 18; break;
    case 4: coeffs = swt_cf_coif4; size = 24; break;
    case 5: coeffs = swt_cf_coif5; size = 30; break;
    }
    break;
  }
  if (coeffs == NULL) return NULL;
  if (length != NULL) *length = size;
  return coeffs;
}
